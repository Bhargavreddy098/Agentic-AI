export function createCoreService(owners = {}) {
    const models = {
        'skill': owners.skill ?? createSkillModel(owners),
        'channel-delivery': owners.channelDelivery ?? createChannelDeliveryModel(owners),
        'protocol-connection': owners.protocolConnection ?? createProtocolConnectionModel(owners),
        'remote-task': owners.remoteTask ?? createRemoteTaskModel(owners),
        'fleet-assignment': owners.fleetAssignment ?? createFleetAssignmentModel(owners),
        'restore-report': owners.restoreReport ?? createRestoreReportModel(owners),
        'tool-candidate': owners.toolCandidate ?? createToolCandidateModel(owners),
        'scaffold-candidate': owners.scaffoldCandidate ?? createScaffoldCandidateModel(owners),
        'task-plan': owners.taskPlan ?? createTaskPlanModel(owners),
        'critique-report': owners.critiqueReport ?? createCritiqueReportModel(owners),
        'agent-definition': owners.agentDefinition ?? createAgentDefinitionModel(owners),
        'agent-lifecycle': owners.agentLifecycle ?? createAgentLifecycleModel(owners),
        'trigger': owners.trigger ?? createTriggerModel(owners),
        'schedule': owners.schedule ?? createScheduleModel(owners),
        'approval-quorum': owners.approvalQuorum ?? createApprovalQuorumModel(owners),
        'resource-grant': owners.resourceGrant ?? createResourceGrantModel(owners),
        'action-preview': owners.actionPreview ?? createActionPreviewModel(owners),
        'compensation-plan': owners.compensationPlan ?? createCompensationPlanModel(owners),
        'candidate-comparison': owners.candidateComparison ?? createCandidateComparisonModel(owners),
        'debate-report': owners.debateReport ?? createDebateReportModel(owners),
        'budget-allocation': owners.budgetAllocation ?? createBudgetAllocationModel(owners),
        'credential-binding': owners.credentialBinding ?? createCredentialBindingModel(owners),
        'project': owners.project ?? createProjectModel(owners),
        'workspace-lease': owners.workspaceLease ?? createWorkspaceLeaseModel(owners),
        'artifact': owners.artifact ?? createArtifactModel(owners),
        'specialist-task': owners.specialistTask ?? createSpecialistTaskModel(owners),
        'security-alert': owners.securityAlert ?? createSecurityAlertModel(owners),
        'decision-summary': owners.decisionSummary ?? createDecisionSummaryModel(owners),
        'replay-view': owners.replayView ?? createReplayViewModel(owners),
        'simulation-report': owners.simulationReport ?? createSimulationReportModel(owners),
        'agent-version': owners.agentVersion ?? createAgentVersionModel(owners),
        'agent-release': owners.agentRelease ?? createAgentReleaseModel(owners),
        'swarm-plan': owners.swarmPlan ?? createSwarmPlanModel(owners),
        'conversation-goal': owners.conversationGoal ?? createConversationGoalModel(owners),
    };

    return {
        models,
        ownedFamilies: CORE_OWNED_FAMILIES,
        getModel(family) {
            return models[family] ?? null;
        },
    };
}
